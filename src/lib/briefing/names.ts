function key(s: string): string {
  return s.trim().toLowerCase();
}

export function ruTeam(name: string, short: string): { name: string; short: string } {
  const candidates = [key(name), key(short), key(name.replace(/^fc\s+/i, ""))];
  for (const c of candidates) {
    if (TEAM_RU[c]) return { name: TEAM_RU[c], short: TEAM_RU[c] };
  }
  for (const [needle, ru] of Object.entries(TEAM_RU)) {
    if (needle.length < 4) continue;
    if (candidates.some((c) => c.includes(needle))) return { name: ru, short: ru };
  }
  return { name, short };
}

export function ruLeague(name: string, fallbackShort: string): { name: string; short: string } {
  return LEAGUE_RU[name] ?? { name, short: fallbackShort };
}

