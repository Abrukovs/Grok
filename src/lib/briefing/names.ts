export function ruTennisRound(raw?: string): string {
  const s = (raw || "").toLowerCase();
  if (!s) return "";
  if (/qualif/i.test(s)) return "квал.";
  if (/final/i.test(s) && !/semi|quarter/.test(s)) return "финал";
  if (/semi/i.test(s)) return "1/2";
  if (/quarter/i.test(s)) return "1/4";
  if (/round of 16|r16|1\/8/.test(s)) return "1/8";
  if (/round of 32|r32/.test(s)) return "1/16";
  if (/round of 64|r64/.test(s)) return "1/32";
  return "";
}

export function ruTennis(rawName: string, tour: string): { name: string; short: string } {
  const raw = (rawName || "").trim();
  const tag = tour === "WTA" ? "WTA" : tour === "ATP" ? "ATP" : tour;
  for (const row of TENNIS_EVENTS) {
    if (row.test.test(raw)) {
      let city = row.city;
      if (/japan open/i.test(raw) && !/kinoshita/i.test(raw) && tour === "WTA") city = "Осака";
      if (/us open|australian|ролан|уимблдон|laver|дэвиса|united|итоговый/i.test(city)) {
        return { name: city, short: city };
      }
      const label = `${tag} ${city}`;
      return { name: label, short: label };
    }
  }
  const cleaned = raw
    .replace(/\bpresentado por\b.+$/i, "")
    .replace(/\bpresented by\b.+$/i, "")
    .replace(/\s{2,}/g, " ")
    .trim();
  const label = cleaned ? `${tag} · ${cleaned}` : tag;
  return { name: label, short: label.length > 28 ? `${tag} · ${cleaned.slice(0, 16)}` : label };
}

export function tennisShortName(name: string): string {
  const parts = name.replace(/\./g, " ").split(/\s+/).filter(Boolean);
  if (parts.length <= 1) return name;
  return parts[parts.length - 1];
}

export function isBigClub(name: string, short: string): boolean {
  const blob = `${name} ${short}`.toLowerCase();
  return BIG_NEEDLES.some((n) => blob.includes(n));
}

export function ruLiveCount(n: number): string {
  const n10 = n % 10;
  const n100 = n % 100;
  if (n10 === 1 && n100 !== 11) return `${n} живой матч`;
  if (n10 >= 2 && n10 <= 4 && (n100 < 10 || n100 >= 20)) return `${n} живых матча`;
  return `${n} живых матчей`;
}
